using System.Collections.Generic;
using System.Text;
using Microsoft.CodeAnalysis;

namespace SimulaSharp.CodeGen;

/// <summary>
/// For every model decorated with <c>[References&lt;T&gt;("Name")]</c>, emits the read-only reference accessor and the
/// hidden fill seam. Per attribute it emits a <c>readonly IReference&lt;{T}Ref&gt; __ref_Name</c> backed by a
/// <c>FillableReference&lt;{T}Ref&gt;</c> and a <c>public IReference&lt;{T}Ref&gt; Name =&gt; __ref_Name;</c> accessor
/// (getters only — no <c>Add</c> on the model's surface). It also implements <c>IReferenceWiring.WireReference</c>
/// explicitly: the generated simulator calls it with a <c>RefCollection</c> of pre-wrapped target Refs, which the seam
/// downcasts to the reference's Ref type (valid because a referenced model's Ref implements the companion interface —
/// see <see cref="RefGenerator"/>) and appends to the fillable backing.
/// </summary>
[Generator]
public sealed class ReferenceGenerator : IIncrementalGenerator
{
    private const string ReferencesAttr = "SimulaSharp.Kernel.Attributes.CrossReferenceAttribute`1";
    private const string IReferenceFq = "global::SimulaSharp.Kernel.Primitives.IReference";
    private const string FillableFq = "global::SimulaSharp.Kernel.Primitives.FillableReference";
    private const string RefCollectionFq = "global::SimulaSharp.Kernel.Primitives.RefCollection";
    private const string IReferenceWiring = "global::SimulaSharp.Kernel.Model.IReferenceWiring";
    private static readonly SymbolDisplayFormat Fq = SymbolDisplayFormat.FullyQualifiedFormat;

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var models = context.SyntaxProvider.ForAttributeWithMetadataName(
                ReferencesAttr,
                predicate: static (_, _) => true,
                transform: static (ctx, _) => Build(ctx))
            .Where(static g => g is not null)
            .Select(static (g, _) => g!.Value);

        context.RegisterSourceOutput(models, static (spc, g) => spc.AddSource(g.HintName, g.Source));
    }

    private static (string HintName, string Source)? Build(GeneratorAttributeSyntaxContext ctx)
    {
        if (ctx.TargetSymbol is not INamedTypeSymbol model) return null;

        // (accessor name, fully-qualified Ref element type) per [CrossReference<T>("Name")] on this class.
        var items = new List<(string Name, string RefType)>();
        foreach (var a in ctx.Attributes)
        {
            if (a.AttributeClass is not { TypeArguments.Length: 1 } ac) continue;
            if (a.ConstructorArguments.Length < 1 || a.ConstructorArguments[0].Value is not string name) continue;
            items.Add((name, ac.TypeArguments[0].ToDisplayString(Fq) + "Ref"));   // <T>Ref, by convention
        }
        if (items.Count == 0) return null;

        bool hasNs = !model.ContainingNamespace.IsGlobalNamespace;
        string? ns = hasNs ? model.ContainingNamespace.ToDisplayString() : null;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        if (hasNs) { sb.Append("namespace ").Append(ns).AppendLine(); sb.AppendLine("{"); }
        sb.Append("partial class ").Append(model.Name).Append(" : ").AppendLine(IReferenceWiring);
        sb.AppendLine("{");

        // Backing fillable (typed as the read-only IReference) + read-only accessor, per reference.
        foreach (var (name, refType) in items)
        {
            sb.Append("    private readonly ").Append(IReferenceFq).Append('<').Append(refType).Append("> __ref_").Append(name)
              .Append(" = new ").Append(FillableFq).Append('<').Append(refType).AppendLine(">();");
            sb.Append("    public ").Append(IReferenceFq).Append('<').Append(refType).Append("> ").Append(name)
              .Append(" => __ref_").Append(name).AppendLine(";");
        }

        // The hidden fill seam: downcast the fillable and add each pre-wrapped Ref.
        sb.AppendLine();
        sb.Append("    void ").Append(IReferenceWiring).Append(".WireReference(string member, ").Append(RefCollectionFq).AppendLine(" refs)");
        sb.AppendLine("    {");
        sb.AppendLine("        switch (member)");
        sb.AppendLine("        {");
        foreach (var (name, refType) in items)
        {
            sb.Append("            case \"").Append(name).AppendLine("\":");
            sb.AppendLine("            {");
            sb.Append("                var __fr = (").Append(FillableFq).Append('<').Append(refType).Append(">)__ref_").Append(name).AppendLine(";");
            sb.Append("                foreach (var __r in refs) __fr.Add((").Append(refType).AppendLine(")__r);");
            sb.AppendLine("                break;");
            sb.AppendLine("            }");
        }
        sb.AppendLine("            default: throw new global::System.ArgumentException(\"Unknown reference '\" + member + \"'.\");");
        sb.AppendLine("        }");
        sb.AppendLine("    }");

        sb.AppendLine("}");
        if (hasNs) sb.AppendLine("}");

        string hint = (hasNs ? ns + "." : "") + model.Name + ".Refs.g.cs";
        return (hint, sb.ToString());
    }
}
