using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace SimulaSharp.CodeGen;

/// <summary>
/// For every partial model with <c>Reference&lt;T&gt;</c> members, emits the access side
/// of the reference split: a <c>protected ReferenceAccessor&lt;TRef&gt; _&lt;Name&gt;</c>
/// per reference (the guarded handle the model calls through) and an explicit
/// <c>IReferenceWiring.WireReferences()</c> that builds each accessor from its
/// <c>Reference</c> collection (via <c>ReferenceAccessor.From</c>). The simulator calls
/// <c>WireReferences</c> once the reference collections are populated.
/// </summary>
[Generator]
public sealed class ReferenceAccessorGenerator : IIncrementalGenerator
{
    private const string IModelFullName = "SimulaSharp.Kernel.Model.IModel";
    private const string ReferenceNs = "SimulaSharp.Kernel.Primitives";
    private const string Accessor = "global::SimulaSharp.Kernel.Primitives.ReferenceAccessor";
    private const string IReferenceWiring = "global::SimulaSharp.Kernel.Model.IReferenceWiring";

    private static readonly SymbolDisplayFormat Fq = SymbolDisplayFormat.FullyQualifiedFormat;

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var models = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => node is ClassDeclarationSyntax c && c.Modifiers.Any(SyntaxKind.PartialKeyword),
                transform: static (ctx, _) => Build(ctx))
            .Where(static g => g is not null)
            .Select(static (g, _) => g!.Value);

        context.RegisterSourceOutput(models, static (spc, g) => spc.AddSource(g.HintName, g.Source));
    }

    private static (string HintName, string Source)? Build(GeneratorSyntaxContext ctx)
    {
        if (ctx.SemanticModel.GetDeclaredSymbol((ClassDeclarationSyntax)ctx.Node) is not INamedTypeSymbol model)
            return null;
        if (model.IsGenericType) return null;
        if (!model.AllInterfaces.Any(static i => i.ToDisplayString() == IModelFullName)) return null;

        var first = model.DeclaringSyntaxReferences.FirstOrDefault();
        if (first is null || first.GetSyntax() != ctx.Node) return null;

        // Collect (memberName, elementType) for each Reference<T> member declared on the model.
        var refs = new List<(string Member, ITypeSymbol Element)>();
        foreach (var member in model.GetMembers())
        {
            if (member.DeclaredAccessibility != Accessibility.Public || member.IsStatic) continue;
            ITypeSymbol? type = member switch
            {
                IPropertySymbol p => p.Type,
                IFieldSymbol { IsImplicitlyDeclared: false } f => f.Type,
                _ => null
            };
            if (type is INamedTypeSymbol { Name: "Reference", TypeArguments.Length: 1 } n
                && n.ContainingNamespace.ToDisplayString() == ReferenceNs)
                refs.Add((member.Name, n.TypeArguments[0]));
        }

        if (refs.Count == 0) return null;

        bool hasNamespace = !model.ContainingNamespace.IsGlobalNamespace;
        string? ns = hasNamespace ? model.ContainingNamespace.ToDisplayString() : null;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        if (hasNamespace) { sb.Append("namespace ").Append(ns).AppendLine(); sb.AppendLine("{"); }
        sb.Append("partial class ").Append(model.Name).Append(" : ").AppendLine(IReferenceWiring);
        sb.AppendLine("{");

        foreach (var (member, element) in refs)
        {
            string refType = element.ToDisplayString(Fq) + "Ref";   // <T>Ref, by convention
            sb.Append("    protected ").Append(Accessor).Append('<').Append(refType).Append("> _").Append(member).AppendLine(" = null!;");
        }

        sb.AppendLine();
        sb.Append("    void ").Append(IReferenceWiring).AppendLine(".WireReferences()");
        sb.AppendLine("    {");
        foreach (var (member, element) in refs)
        {
            string refType = element.ToDisplayString(Fq) + "Ref";
            sb.Append("        _").Append(member).Append(" = ").Append(Accessor).Append(".From(").Append(member)
              .Append(", static __m => new ").Append(refType).AppendLine("(__m));");
        }
        sb.AppendLine("    }");

        sb.AppendLine("}");
        if (hasNamespace) sb.AppendLine("}");

        string hint = (hasNamespace ? ns + "." : "") + model.Name + ".Refs.g.cs";
        return (hint, sb.ToString());
    }
}
