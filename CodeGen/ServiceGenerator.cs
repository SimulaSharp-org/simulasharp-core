using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace SimulaSharp.CodeGen;

/// <summary>
/// Emits the interaction plumbing for services (types implementing
/// <c>SimulaSharp.Kernel.Model.IService</c>, declared <c>partial</c>):
/// <list type="bullet">
///   <item>For each <c>[ServiceEvent("X", argType?)]</c> — a fire-and-forget publish
///   point — a backing <c>ServiceEventChannel</c>, a public
///   <c>RegisterCallback_X(dispatcher, callback)</c> for subscribers (the subscriber
///   passes its site's <c>IDispatcher</c>), and a protected <c>Trigger_X(...)</c> the
///   service calls to publish (Posts each callback onto its subscriber's dispatcher).
///   Returning events (a result type) are not yet generated.</item>
///   <item>For each <c>[ServiceRequest]</c> method <c>Handle_X(..)</c> — a public
///   <c>X(..)</c> caller that marshals the call onto the service's own site
///   (<c>Site.Inject*</c>, the common <c>IDispatcher</c> facet, so it works on both the
///   sim-paced and loosely-coupled service bases) and returns an awaitable
///   (<c>Task</c>/<c>Task&lt;T&gt;</c>).</item>
/// </list>
/// </summary>
[Generator]
public sealed class ServiceGenerator : IIncrementalGenerator
{
    private const string IServiceFullName = "SimulaSharp.Kernel.Model.IService";
    private const string ServiceEventAttr = "SimulaSharp.Kernel.Attributes.ServiceEventAttribute";
    private const string ServiceRequestAttr = "SimulaSharp.Kernel.Attributes.ServiceRequestAttribute";

    private const string Sched = "global::SimulaSharp.Kernel.Services.IDispatcher";
    private const string Chan = "global::SimulaSharp.Kernel.Services.ServiceEventChannel";
    private const string Task = "global::System.Threading.Tasks.Task";
    private const string Act = "global::System.Action";

    private static readonly SymbolDisplayFormat Fq = SymbolDisplayFormat.FullyQualifiedFormat;

    private static readonly DiagnosticDescriptor ServiceRequestTooManyParams = new("SIM022",
        "A service request takes at most one context parameter",
        "[ServiceRequest] method '{0}' has more than one parameter — a request carries a single optional context; reduce it to zero or one parameter",
        "SimulaSharp.Assembly", DiagnosticSeverity.Error, isEnabledByDefault: true);

    /// <summary>A diagnostic to raise on the output side, carried out of the transform (which cannot report).</summary>
    private readonly struct DiagInfo
    {
        public readonly string MethodName;
        public readonly Location Location;
        public DiagInfo(string methodName, Location location) { MethodName = methodName; Location = location; }
    }

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var services = context.SyntaxProvider
            .CreateSyntaxProvider(
                predicate: static (node, _) => node is ClassDeclarationSyntax c && c.Modifiers.Any(SyntaxKind.PartialKeyword),
                transform: static (ctx, _) => Build(ctx))
            .Where(static g => g is not null)
            .Select(static (g, _) => g!.Value);

        context.RegisterSourceOutput(services, static (spc, g) =>
        {
            foreach (var d in g.Diags)
                spc.ReportDiagnostic(Diagnostic.Create(ServiceRequestTooManyParams, d.Location, d.MethodName));
            if (g.Source.Length > 0) spc.AddSource(g.HintName, g.Source);
        });
    }

    private static (string HintName, string Source, ImmutableArray<DiagInfo> Diags)? Build(GeneratorSyntaxContext ctx)
    {
        if (ctx.SemanticModel.GetDeclaredSymbol((ClassDeclarationSyntax)ctx.Node) is not INamedTypeSymbol service)
            return null;
        if (service.IsGenericType) return null;
        if (!service.AllInterfaces.Any(static i => i.ToDisplayString() == IServiceFullName)) return null;

        // Emit once per service even if it has several partial parts (first declaration wins).
        var first = service.DeclaringSyntaxReferences.FirstOrDefault();
        if (first is null || first.GetSyntax() != ctx.Node) return null;

        var body = new StringBuilder();
        var diags = new List<DiagInfo>();
        EmitEvents(body, service);
        EmitRequests(body, diags, service);
        if (body.Length == 0)   // nothing to emit; still surface any diagnostics we collected
            return diags.Count == 0 ? null : ("", "", diags.ToImmutableArray());

        bool hasNamespace = !service.ContainingNamespace.IsGlobalNamespace;
        string? ns = hasNamespace ? service.ContainingNamespace.ToDisplayString() : null;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        if (hasNamespace)
        {
            sb.Append("namespace ").Append(ns).AppendLine();
            sb.AppendLine("{");
        }
        sb.Append("partial class ").Append(service.Name).AppendLine();
        sb.AppendLine("{");
        sb.Append(body);
        sb.AppendLine("}");
        if (hasNamespace) sb.AppendLine("}");

        string hint = (hasNamespace ? ns + "." : "") + service.Name + ".Service.g.cs";
        return (hint, sb.ToString(), diags.ToImmutableArray());
    }

    private static void EmitEvents(StringBuilder sb, INamedTypeSymbol service)
    {
        foreach (var attr in service.GetAttributes())
        {
            if (attr.AttributeClass?.ToDisplayString() != ServiceEventAttr) continue;
            var args = attr.ConstructorArguments;
            if (args.Length == 0 || args[0].Value is not string name) continue;

            var argType = args.Length > 1 ? args[1].Value as ITypeSymbol : null;

            sb.AppendLine();
            if (argType is null)
            {
                sb.Append("    private readonly ").Append(Chan).Append(" __evt_").Append(name).AppendLine(" = new();");
                sb.Append("    public void RegisterCallback_").Append(name).Append('(').Append(Sched)
                  .Append(" dispatcher, ").Append(Act).Append(" callback) => __evt_").Append(name).AppendLine(".Register(dispatcher, callback);");
                sb.Append("    protected void Trigger_").Append(name).Append("() => __evt_").Append(name).AppendLine(".Trigger();");
            }
            else
            {
                string t = argType.ToDisplayString(Fq);
                sb.Append("    private readonly ").Append(Chan).Append('<').Append(t).Append("> __evt_").Append(name).AppendLine(" = new();");
                sb.Append("    public void RegisterCallback_").Append(name).Append('(').Append(Sched)
                  .Append(" dispatcher, ").Append(Act).Append('<').Append(t).Append("> callback) => __evt_").Append(name).AppendLine(".Register(dispatcher, callback);");
                sb.Append("    protected void Trigger_").Append(name).Append('(').Append(t).Append(" value) => __evt_").Append(name).AppendLine(".Trigger(value);");
            }
        }
    }

    private static void EmitRequests(StringBuilder sb, List<DiagInfo> diags, INamedTypeSymbol service)
    {
        foreach (var member in service.GetMembers())
        {
            if (member is not IMethodSymbol { MethodKind: MethodKind.Ordinary } m) continue;
            var attr = m.GetAttributes().FirstOrDefault(static a => a.AttributeClass?.ToDisplayString() == ServiceRequestAttr);
            if (attr is null) continue;
            if (m.IsGenericMethod || m.Parameters.Any(static p => p.RefKind != RefKind.None)) continue;

            // A request carries a single optional context — more than one parameter is an error (SIM022). Skip
            // emitting the caller for the malformed handler; the diagnostic is reported on the output side.
            if (m.Parameters.Length > 1)
            {
                diags.Add(new DiagInfo(m.Name, m.Locations.FirstOrDefault() ?? Location.None));
                continue;
            }

            string requestName =
                attr.ConstructorArguments.Length > 0 && attr.ConstructorArguments[0].Value is string n ? n
                : m.Name.StartsWith("Handle_") ? m.Name.Substring("Handle_".Length)
                : m.Name;

            var (decls, args) = Params(m.Parameters);
            string invoke = m.Name + "(" + args + ")";

            sb.AppendLine();
            if (m.ReturnsVoid)
            {
                sb.Append("    public ").Append(Task).Append(' ').Append(requestName).Append('(').Append(decls)
                  .Append(") => Site.InjectVoidAsync(() => ").Append(invoke).AppendLine(");");
            }
            else
            {
                sb.Append("    public ").Append(Task).Append('<').Append(m.ReturnType.ToDisplayString(Fq)).Append("> ")
                  .Append(requestName).Append('(').Append(decls)
                  .Append(") => Site.InjectAsync(() => ").Append(invoke).AppendLine(");");
            }
        }
    }

    private static (string Decls, string Args) Params(IReadOnlyList<IParameterSymbol> ps)
    {
        var decls = new StringBuilder();
        var args = new StringBuilder();
        for (int i = 0; i < ps.Count; i++)
        {
            if (i > 0) { decls.Append(", "); args.Append(", "); }
            decls.Append(ps[i].Type.ToDisplayString(Fq)).Append(' ').Append(ps[i].Name);
            args.Append(ps[i].Name);
        }
        return (decls.ToString(), args.ToString());
    }
}
