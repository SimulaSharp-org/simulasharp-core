using System.Collections.Generic;
using System.Text;
using Microsoft.CodeAnalysis;

namespace SimulaSharp.CodeGen;

/// <summary>
/// For every model decorated with <c>[Reference&lt;T&gt;("Name")]</c> (an <b>intra-site</b> reference), emits the
/// read-only list accessor and the hidden fill seam. Because the targets share this model's SimSite, there is no Ref
/// wrapping and no marshalling: per attribute it emits a <c>private readonly List&lt;T&gt; __local_Name</c> and a
/// <c>public IReadOnlyList&lt;T&gt; Name =&gt; __local_Name;</c> accessor (getters only). It implements
/// <c>ILocalReferenceWiring.WireLocalReference</c> explicitly — the generated simulator calls it after construction
/// with the target <c>IModel</c> instances themselves, which the seam casts to the reference's element type and
/// appends. (Contrast <see cref="ReferenceGenerator"/>, the cross-site variant over guarded Refs.)
/// </summary>
[Generator]
public sealed class LocalReferenceGenerator : IIncrementalGenerator
{
    private const string ReferenceAttr = "SimulaSharp.Kernel.Attributes.ReferenceAttribute`1";
    private const string IModelFq = "global::SimulaSharp.Kernel.Model.IModel";
    private const string ILocalWiring = "global::SimulaSharp.Kernel.Model.ILocalReferenceWiring";
    private const string ListFq = "global::System.Collections.Generic.List";
    private const string IReadOnlyListFq = "global::System.Collections.Generic.IReadOnlyList";
    private static readonly SymbolDisplayFormat Fq = SymbolDisplayFormat.FullyQualifiedFormat;

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var models = context.SyntaxProvider.ForAttributeWithMetadataName(
                ReferenceAttr,
                predicate: static (_, _) => true,
                transform: static (ctx, _) => Build(ctx))
            .Where(static g => g is not null)
            .Select(static (g, _) => g!.Value);

        context.RegisterSourceOutput(models, static (spc, g) => spc.AddSource(g.HintName, g.Source));
    }

    private static (string HintName, string Source)? Build(GeneratorAttributeSyntaxContext ctx)
    {
        if (ctx.TargetSymbol is not INamedTypeSymbol model) return null;

        // (accessor name, fully-qualified element type) per [Reference<T>("Name")] on this class.
        var items = new List<(string Name, string Elem)>();
        foreach (var a in ctx.Attributes)
        {
            if (a.AttributeClass is not { TypeArguments.Length: 1 } ac) continue;
            if (a.ConstructorArguments.Length < 1 || a.ConstructorArguments[0].Value is not string name) continue;
            items.Add((name, ac.TypeArguments[0].ToDisplayString(Fq)));
        }
        if (items.Count == 0) return null;

        bool hasNs = !model.ContainingNamespace.IsGlobalNamespace;
        string? ns = hasNs ? model.ContainingNamespace.ToDisplayString() : null;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        if (hasNs) { sb.Append("namespace ").Append(ns).AppendLine(); sb.AppendLine("{"); }
        sb.Append("partial class ").Append(model.Name).Append(" : ").AppendLine(ILocalWiring);
        sb.AppendLine("{");

        // Backing list (the actual same-site instances) + read-only accessor, per reference.
        foreach (var (name, elem) in items)
        {
            sb.Append("    private readonly ").Append(ListFq).Append('<').Append(elem).Append("> __local_").Append(name)
              .Append(" = new ").Append(ListFq).Append('<').Append(elem).AppendLine(">();");
            sb.Append("    public ").Append(IReadOnlyListFq).Append('<').Append(elem).Append("> ").Append(name)
              .Append(" => __local_").Append(name).AppendLine(";");
        }

        // The hidden fill seam: cast each same-site target instance to the element type and add it.
        sb.AppendLine();
        sb.Append("    void ").Append(ILocalWiring).Append(".WireLocalReference(string member, ")
          .Append(IReadOnlyListFq).Append('<').Append(IModelFq).AppendLine("> targets)");
        sb.AppendLine("    {");
        sb.AppendLine("        switch (member)");
        sb.AppendLine("        {");
        foreach (var (name, elem) in items)
        {
            sb.Append("            case \"").Append(name).AppendLine("\":");
            sb.Append("                foreach (var __m in targets) __local_").Append(name).Append(".Add((").Append(elem).AppendLine(")__m);");
            sb.AppendLine("                break;");
        }
        sb.AppendLine("            default: throw new global::System.ArgumentException(\"Unknown reference '\" + member + \"'.\");");
        sb.AppendLine("        }");
        sb.AppendLine("    }");

        sb.AppendLine("}");
        if (hasNs) sb.AppendLine("}");

        string hint = (hasNs ? ns + "." : "") + model.Name + ".LocalRefs.g.cs";
        return (hint, sb.ToString());
    }
}
